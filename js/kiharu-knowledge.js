window.KIHARU_KNOWLEDGE.answer = function(query) {
  var db = this;
  var q = String(query || '').toLowerCase().replace(/&/g, ' and ')
    .replace(/programmes?/g, 'programme').replace(/courses?/g, 'course').replace(/fees?/g, 'fee')
    .replace(/applications?/g, 'application').replace(/admissions?/g, 'admission').replace(/modules?/g, 'module')
    .replace(/tenders?/g, 'tender').replace(/vacancies/g, 'vacancy').replace(/accredited/g, 'accreditation')
    .replace(/\bprogram\b/g, 'programme').replace(/\bapply\b/g, 'application')
    .replace(/\bwhere\b|\bdirections?\b/g, 'location').replace(/\bphone\b|\bcall\b/g, 'contact')
    .replace(/\s+/g, ' ').trim();
  if (!q) return db.fallback;
  var names = Object.keys(db.programmes);
  var course = names.find(function(name) {
    var n = name.toLowerCase().replace(/&/g, ' and ');
    return q.indexOf(n) >= 0 || n.split(/\s+/).some(function(part) { return part.length > 5 && q.indexOf(part) >= 0; });
  });
  if (course && /module|unit|curriculum|study|learn/.test(q)) {
    return course + ' modules and units:\n' + db.programmes[course].modules.map(function(m, i) {
      return (i + 1) + '. ' + m.title + ': ' + m.name + ' — ' + m.units.join('; ');
    }).join('\n');
  }
  if (course) {
    var entry = db.knowledgeEntries.find(function(item) { return item.id === db.programmes[course].slug; });
    return entry ? entry.text : course + ' is offered at Kiharu TVC.';
  }
  if (/\bjobs?\b|\bvacancy\b|employment|career/.test(q)) return db.jobs;
  if (/tender|procurement|supplier|bid/.test(q)) return db.tenders;
  if (/fee|payment|bank|cheque|cash|cost/.test(q)) return db.fees.details;
  if (/entry|requirement|eligib|kcse|kcpe/.test(q)) return db.entryRequirements.details;
  if (/application|admission|intake/.test(q)) return db.admissions.details;
  if (/short course|short-course|rolling/.test(q)) return 'Kiharu TVC offers these short courses:\n' + db.shortCourses.map(function(x, i) { return (i + 1) + '. ' + x; }).join('\n') + '\nShort courses have rolling admissions.';
  if (/accreditation|tveta|cdacc/.test(q)) return db.accreditation;
  if (/charter|service standard/.test(q)) return db.serviceCharter;
  if (/location|address|murang|gaturi|kiambugi|road|map/.test(q)) return db.location + '\n\n' + db.contact;
  if (/contact|postal|email/.test(q)) return db.contact;
  if (/course|programme|study|offer|available/.test(q)) return 'Kiharu TVC offers these programme areas:\n' + names.map(function(n, i) { return (i + 1) + '. ' + n; }).join('\n') + '\n\nShort courses are also available:\n' + db.shortCourses.join(', ') + '.';
  if (/overview|about/.test(q) || /^kiharu tvc$/.test(q)) return db.overview;
  return db.fallback;
};
